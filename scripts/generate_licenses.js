// Regenerates the third-party license list from what is really installed:
//   - THIRD_PARTY_LICENSES.txt                        (full texts, shipped with a release)
//   - client/src/generated/third-party.json           (name/version/license/url, shown in the About page)
//   - client/src/generated/license.json               (the project's own LICENSE, shown in the About page)
//
// Prerequisites: `npm install` in client/ and scripts/, and a server/.venv with pip-licenses
// (pip install -r server/requirements-dev.txt).
// Run it with: npm run generate-licenses --prefix scripts

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const clientDir = path.join(root, "client");
const serverDir = path.join(root, "server");
const npx = process.platform === "win32" ? "npx.cmd" : "npx";

function serverPython() {
  const venv = process.platform === "win32" ? ["Scripts", "python.exe"] : ["bin", "python"];
  const candidate = path.join(serverDir, ".venv", ...venv);
  return process.env.PYTHON || (fs.existsSync(candidate) ? candidate : "python");
}

function readClientLicenses() {
  // production dependencies only: what ends up in the built interface
  const output = execFileSync(
    npx,
    ["license-checker", "--production", "--excludePrivatePackages", "--start", clientDir, "--json"],
    { cwd: __dirname, encoding: "utf8", maxBuffer: 256 * 1024 * 1024, shell: process.platform === "win32" }
  );
  return Object.entries(JSON.parse(output))
    .map(([id, info]) => {
      const at = id.lastIndexOf("@");
      return {
        name: id.slice(0, at),
        version: id.slice(at + 1),
        license: String(info.licenses),
        url: info.repository || info.url || "",
        author: info.publisher || "",
        text: info.licenseFile && fs.existsSync(info.licenseFile) ? fs.readFileSync(info.licenseFile, "utf8") : "",
        side: "client",
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

// Names of the packages requirements.txt needs, transitive ones included (dev tools are left out).
const CLOSURE = `
import json, re, sys
from importlib.metadata import PackageNotFoundError, requires, version

def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()

seen, todo = set(), []
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.split("#")[0].strip()
    if line and not line.startswith("-"):
        todo.append(re.split(r"[\\[=<>~!; ]", line)[0])
while todo:
    name = norm(todo.pop())
    if name in seen:
        continue
    seen.add(name)
    try:
        version(name)
        for requirement in requires(name) or []:
            if "extra ==" not in requirement:
                todo.append(re.split(r"[\\[=<>~!; (]", requirement)[0])
    except PackageNotFoundError:
        pass
print(json.dumps(sorted(seen)))
`;

function readServerLicenses() {
  const python = serverPython();
  const needed = new Set(
    JSON.parse(execFileSync(python, ["-c", CLOSURE, path.join(serverDir, "requirements.txt")], { encoding: "utf8" }))
  );
  const output = execFileSync(
    python,
    ["-m", "piplicenses", "--format=json", "--with-urls", "--with-authors", "--with-license-file", "--no-license-path"],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 }
  );
  const known = (value) => (value && value !== "UNKNOWN" ? value : "");
  return JSON.parse(output)
    .filter((p) => needed.has(String(p.Name).toLowerCase().replace(/[-_.]+/g, "-")))
    .map((p) => ({
      name: p.Name,
      version: p.Version,
      license: p.License,
      url: known(p.URL),
      author: known(p.Author),
      text: known(p.LicenseText),
      side: "server",
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function writeText(packages) {
  const rule = "*".repeat(81);
  const banner = (title) => `${rule}\n${title.padStart(41 + Math.floor(title.length / 2), "*").padEnd(81, "*")}\n${rule}\n\n`;
  let out = "THIRD PARTY LICENSES\n\n";
  out += "This document was programmatically generated by scripts/generate_licenses.js\n\n";
  out += "This product includes software developed by the following third parties:\n\n";

  let count = 1;
  for (const side of ["client", "server"]) {
    out += banner(` ${side.toUpperCase()} SIDE THIRD PARTY LICENSES `);
    for (const p of packages.filter((x) => x.side === side)) {
      out += `${count}. Library Name: ${p.name}@${p.version}\n`;
      out += `   License: ${p.license}\n`;
      out += `   Publisher: ${p.author || "Unknown"}\n`;
      out += `   URL: ${p.url || "Unknown"}\n\n`;
      out += `   ${p.text ? p.text.trim().replace(/\r?\n/g, "\n   ") : "License text not found."}\n`;
      out += `${"_".repeat(80)}\n\n`;
      count += 1;
    }
  }
  fs.writeFileSync(path.join(root, "THIRD_PARTY_LICENSES.txt"), out);
}

function writeJson(packages) {
  const target = path.join(clientDir, "src", "generated", "third-party.json");
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const list = packages.map(({ name, version, license, url, side }) => ({ name, version, license, url, side }));
  fs.writeFileSync(target, JSON.stringify(list, null, 2) + "\n");
}

const packages = [...readClientLicenses(), ...readServerLicenses()];
writeText(packages);
writeJson(packages);
console.log(`${packages.length} packages written (THIRD_PARTY_LICENSES.txt, client/src/generated/third-party.json)`);
